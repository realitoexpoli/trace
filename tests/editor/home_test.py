"""Run: python3 tests/editor/home_test.py <editor URL, e.g. file:///path/trace.html>
The projects page: templates, project cards, search, sort, rename, duplicate, delete, and moving between the page and the editor."""
import asyncio, sys
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'file:///tmp/trace_test.html'
passed = []
def check(ok, what):
    if not ok: raise AssertionError('FAIL: ' + what)
    passed.append(what); print('  ok ', what, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); errs = []
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
        await ctx.add_init_script("try{localStorage.setItem('trace-toured','1')}catch(e){}")
        pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(URL.split('#')[0]); await pg.wait_for_timeout(7000)
        check(await pg.is_visible('#home') and not await pg.is_visible('header'), 'the app opens on the projects page, without the editor')
        check(await pg.evaluate("location.hash") == '#projects', 'the address says #projects')
        n = await pg.evaluate("document.querySelectorAll('#tplGrid .tpl').length")
        check(n >= 9, f'{n} templates to start from')
        check(await pg.evaluate("document.querySelectorAll('#tplGrid .tpl-th>svg').length") >= 8, 'templates show a preview of their first slide')
        check(await pg.evaluate("document.querySelectorAll('#projGrid .pcard').length") == 1, 'the existing project is listed')
        await pg.click('[data-tpl="orbit"]'); await pg.wait_for_timeout(1200)
        check(await pg.is_visible('header') and not await pg.is_visible('#home') and await pg.evaluate("location.hash") == '#edit', 'a template opens in the editor')
        check(await pg.evaluate("curMeta().name") == 'Orbit' and await pg.evaluate("slide().objects.some(o=>o.lib==='rocket'&&o.paths)"), 'the new project is made from the template')
        await pg.go_back(); await pg.wait_for_timeout(1500)
        check(await pg.is_visible('#home'), 'the browser’s Back button returns to the projects page')
        await pg.go_forward(); await pg.wait_for_timeout(800)
        check(await pg.is_visible('header'), 'and Forward goes back to the editor')
        await pg.click('#homeBtn'); await pg.wait_for_timeout(1500)
        check(await pg.is_visible('#home'), 'the logo in the editor opens the projects page')
        cards = await pg.evaluate("[...document.querySelectorAll('#projGrid .pcard b')].map(b=>b.textContent)")
        check(cards[0] == 'Orbit' and len(cards) == 2, f'the newest project comes first {cards}')
        check(await pg.evaluate("!!document.querySelector('#projGrid .pcard .pc-th>svg')"), 'project cards show a preview')
        await pg.fill('#homeSearch', 'orb'); await pg.wait_for_timeout(200)
        check(await pg.evaluate("document.querySelectorAll('#projGrid .pcard').length") == 1, 'search filters the projects')
        await pg.fill('#homeSearch', 'zzz'); await pg.wait_for_timeout(200)
        check('No project matches' in await pg.inner_text('#projGrid'), 'an empty search says so')
        await pg.fill('#homeSearch', ''); await pg.wait_for_timeout(200)
        await pg.select_option('#homeSort', 'name'); await pg.wait_for_timeout(200)
        check(await pg.evaluate("[...document.querySelectorAll('#projGrid .pcard b')].map(b=>b.textContent).join()") == 'Orbit,Untitled project', 'sort by name')
        oid = await pg.evaluate("projects.find(p=>p.name==='Orbit').id")
        await pg.click(f'.pcard[data-pid="{oid}"] .pc-more'); await pg.click(f'.pcard[data-pid="{oid}"] [data-pact="rename"]')
        await pg.fill('.pc-rename', 'Rocket orbit'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(300)
        check(await pg.evaluate(f"projects.find(p=>p.id==='{oid}').name") == 'Rocket orbit', 'rename from the card')
        await pg.click(f'.pcard[data-pid="{oid}"] .pc-more'); await pg.click(f'.pcard[data-pid="{oid}"] [data-pact="dup"]'); await pg.wait_for_timeout(500)
        check(await pg.evaluate("projects.some(p=>p.name==='Rocket orbit copy')") and await pg.is_visible('#home'), 'duplicate from the card, staying on the page')
        cid = await pg.evaluate("projects.find(p=>p.name==='Rocket orbit copy').id")
        await pg.click(f'.pcard[data-pid="{cid}"] .pc-more'); await pg.click(f'.pcard[data-pid="{cid}"] [data-pact="delete"]'); await pg.wait_for_timeout(200)
        check(await pg.evaluate(f"projects.some(p=>p.id==='{cid}')") and 'again' in await pg.inner_text(f'.pcard[data-pid="{cid}"] [data-pact="delete"]'), 'Delete asks for a second click')
        await pg.click(f'.pcard[data-pid="{cid}"] [data-pact="delete"]'); await pg.wait_for_timeout(500)
        check(not await pg.evaluate(f"projects.some(p=>p.id==='{cid}')"), 'the second click deletes it')
        await pg.click(f'.pcard[data-pid="{oid}"] .pc-open'); await pg.wait_for_timeout(800)
        check(await pg.evaluate("curMeta().name") == 'Rocket orbit' and await pg.is_visible('header'), 'clicking a card opens it in the editor')
        await pg.click('#homeBtn'); await pg.wait_for_timeout(800)
        await pg.click('#homeTut [data-tour]'); await pg.wait_for_timeout(800)
        check(await pg.is_visible('header') and await pg.evaluate("!!tour"), 'Start the tutorial opens the editor and the first chapter')
        await pg.evaluate("endTour()")
        # opening /app#edit goes straight to the editor
        await pg.goto(URL.split('#')[0] + '#edit'); await pg.wait_for_timeout(1500)
        check(await pg.is_visible('header') and not await pg.is_visible('#home'), '#edit opens the editor directly')
        # Export is a visible header button with every format
        check(await pg.is_visible('[data-menu="export"]') and not await pg.is_visible('#exportBtn'), 'the header has an Export button')
        await pg.click('[data-menu="export"]'); await pg.wait_for_timeout(200)
        check(all([await pg.is_visible(x) for x in ['#videoBtn', '#pdfBtn', '#pngBtn', '#exportBtn', '#manimBtn', '#importBtn']]), 'Export offers video, PDF, picture, the project file, the Python script and Import')
        await pg.keyboard.press('Escape')
        check(await pg.evaluate("document.querySelector('header').getBoundingClientRect().height") < 60, 'the header fits on one line on a laptop')
        await ctx.close()
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        await ctx.add_init_script("try{localStorage.setItem('trace-toured','1')}catch(e){}")
        pg = await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(URL.split('#')[0]); await pg.wait_for_timeout(2500)
        check(await pg.evaluate("document.documentElement.scrollWidth<=innerWidth"), 'on a phone the projects page fits the screen')
        check(not errs, 'no script errors ' + '; '.join(errs))
        await b.close()
    print(f'\nALL {len(passed)} PROJECTS-PAGE CHECKS PASSED')
asyncio.run(main())

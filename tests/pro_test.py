"""Run: python3 tests/editor/pro_test.py <editor URL, e.g. file:///path/trace.html>
Pro features in the editor: white work area, PRO gates for a free account, Present badge, recorded voice."""
import asyncio, sys
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'file:///tmp/trace_test.html'
passed = []
def check(ok, what):
    if not ok: raise AssertionError('FAIL: ' + what)
    passed.append(what); print('  ok ', what, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--autoplay-policy=no-user-gesture-required'])
        for scheme in ['light', 'dark']:
            ctx = await b.new_context(viewport={'width': 1440, 'height': 860}, color_scheme=scheme)
            await ctx.add_init_script("try{localStorage.setItem('trace-toured','1')}catch(e){}")
            pg = await ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
            await pg.goto(URL + '#edit'); await pg.wait_for_timeout(1200)
            bgs = await pg.evaluate("[getComputedStyle(document.querySelector('.stage')).backgroundColor,getComputedStyle(document.querySelector('#props')||document.body).backgroundColor,getComputedStyle(document.body).backgroundColor]")
            check(all(c == 'rgb(255, 255, 255)' for c in bgs), f'the work area and panels are white ({scheme} device setting) {bgs}')
            await ctx.close()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 860})
        await ctx.add_init_script("try{localStorage.setItem('trace-toured','1')}catch(e){}")
        pg = await ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(URL + '#edit'); await pg.wait_for_timeout(1200)
        await pg.evaluate("()=>{createProject('Pro test',blankDeck());refresh();}")
        # on its own the editor has everything
        check(await pg.evaluate("document.body.classList.contains('is-pro') && getComputedStyle(document.querySelector('#tools .protag')).display==='none'"), 'the stand-alone editor shows no PRO tags')
        await pg.evaluate("addObj('axes3d')"); check(await pg.evaluate("slide().objects.some(o=>o.type==='axes3d')"), 'the stand-alone editor adds a 3D surface')
        # voice: record on Opens
        await pg.evaluate("()=>{editStep=0;renderCanvas();renderStepBar();}")
        await pg.click('#vRec'); await pg.wait_for_timeout(1600)
        check(await pg.evaluate("!!rec && document.querySelector('#vRec').textContent.includes('Stop')"), 'Record voice starts recording and shows Stop')
        await pg.click('#vRec'); await pg.wait_for_timeout(800)
        v = await pg.evaluate("slide().voice&&slide().voice[0]")
        check(v and v['dur'] >= 1, f'stopping keeps the recording on the step {v}')
        check(await pg.evaluate("IMG.get(slide().voice[0].id).startsWith('data:audio/')"), 'the sound is stored with the deck media')
        check(await pg.evaluate("!!document.querySelector('#stepbar [data-step=\"0\"] .vmark')"), 'the step shows a microphone mark')
        check(await pg.evaluate("Object.keys(deckWithImages(deck).images||{}).some(k=>k.startsWith('voice_'))"), 'saving or sharing the deck carries the voice')
        await pg.click('#vPlay'); await pg.wait_for_timeout(300)
        check(await pg.evaluate("!!voiceAudio && !voiceAudio.paused"), '▶ Voice plays it back')
        await pg.evaluate("voiceStop()")
        await pg.click('#presentBtn'); await pg.wait_for_timeout(500)
        check(await pg.evaluate("!!voiceAudio && !voiceAudio.paused"), 'presenting plays the voice of the step')
        check(await pg.evaluate("document.querySelector('#pbadge').hidden"), 'no badge while presenting in the stand-alone editor')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        check(await pg.evaluate("!voiceAudio"), 'leaving Present stops the voice')
        # Re-record and delete
        await pg.evaluate("()=>{editStep=0;renderStepBar();}")
        await pg.click('#vDel'); await pg.wait_for_timeout(200)
        check(await pg.evaluate("!slide().voice"), '× deletes the voice')
        # free account
        await pg.evaluate("()=>{PLAN.pro=false;PLAN.badge=true;window.__up=[];PLAN.upgrade=w=>__up.push(w);planChanged();}")
        check(await pg.evaluate("getComputedStyle(document.querySelector('#tools [data-t=\"axes3d\"] .protag')).display!=='none'"), 'a free account sees PRO on advanced 3D')
        check(await pg.evaluate("!document.querySelector('#tools [data-t=\"sphere3\"] .protag')"), 'basic 3D shapes stay free')
        n = await pg.evaluate("slide().objects.length")
        await pg.evaluate("addObj('torus3')"); await pg.evaluate("addObj('shapes3d')")
        check(await pg.evaluate(f"slide().objects.length==={n} && __up.join()==='3d,3d'"), 'adding advanced 3D asks to upgrade instead')
        await pg.evaluate("()=>{sel=null;addObj('sphere3')}"); check(await pg.evaluate(f"slide().objects.length==={n+1}"), 'a sphere can still be added on Free')
        await pg.evaluate("()=>{addObj('latex');const q=slide().objects.at(-1);q.src='z = sin(x) cos(y)';syncAll();plotEquation(q);}")
        check(await pg.evaluate("__up.at(-1)==='3d' && !slide().objects.some(o=>o.type==='axes3d'&&o.source)"), 'plotting a 3D surface asks to upgrade')
        await pg.evaluate("()=>{__up=[];document.querySelector('#exportBtn').click();}"); await pg.wait_for_timeout(200)
        check(await pg.evaluate("!document.querySelector('#modal').hidden && tab==='json' && document.querySelector('.tab[data-tab=\"code\"]').classList.contains('locked')"), 'Export opens the deck file; the Python script is marked PRO')
        await pg.click('.tab[data-tab="code"]'); await pg.wait_for_timeout(200)
        check(await pg.evaluate("__up.includes('python') && tab==='json'"), 'the Python tab asks to upgrade')
        await pg.evaluate("document.querySelector('#modal').hidden=true")
        await pg.evaluate("()=>{editStep=0;renderStepBar();__up=[];}")
        await pg.click('#vRec'); await pg.wait_for_timeout(300)
        check(await pg.evaluate("__up.includes('voice') && !rec"), 'Record voice asks to upgrade on Free')
        await pg.evaluate("()=>{const a=slide().objects.find(o=>o.type==='axes3d');}")
        await pg.click('#presentBtn'); await pg.wait_for_timeout(400)
        check(await pg.evaluate("!document.querySelector('#pbadge').hidden && document.querySelector('#pbadge').getBoundingClientRect().width>0"), 'a free account shows “Made with Tracé” while presenting')
        await pg.mouse.click(720, 400); await pg.wait_for_timeout(200)
        await pg.keyboard.press('Escape')
        # python watermark when free accounts may export python
        await pg.evaluate("()=>{PLAN.pythonFree=true;planChanged();}")
        code = await pg.evaluate("genCode()")
        check('Made with Tracé' in code and 'add_foreground_mobject(mark)' in code, 'free Python scripts carry the corner mark')
        await pg.evaluate("()=>{PLAN.pro=true;planChanged();}")
        check('add_foreground_mobject(mark)' not in await pg.evaluate("genCode()"), 'Pro Python scripts have no mark')
        check(not errs, 'no script errors ' + '; '.join(errs))
        await b.close()
    print(f'\nALL {len(passed)} PRO-FEATURE CHECKS PASSED')
asyncio.run(main())
